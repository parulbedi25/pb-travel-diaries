/**
 * The schema as PHP has to run it, taken from the one place that defines it.
 *
 * The PHP bootstrap creates the tables on a static deployment, and the Node app
 * then serves every request against them. Two hand-written schemas would drift
 * the moment a migration was added — the site would look fine and one feature
 * would fail in the dashboard. So PHP does not own a schema at all: it runs
 * exactly the statements Node would run, and records the same ledger rows.
 *
 * `npm run export:static -- --php` bakes the two lists below into `api.php`:
 *
 *   mysql   BASE_STATEMENTS, then every migration's statements, then the
 *           ledger row for each version (1..LATEST_VERSION) — written for
 *           MariaDB/MySQL, exactly as `server/schema.sql` is.
 *   sqlite  the SQLite migration list, which is already flat statements, and
 *           its own `pb_schema_migrations` ledger.
 *
 * So a database created by PHP is indistinguishable from one created by
 * `npm start` on a fresh copy, which is what makes every endpoint work
 * afterwards.
 */
import { BASE_STATEMENTS, LATEST_VERSION } from "../db/schema.js";
import { MIGRATIONS } from "../db/migrations.js";
import { SQLITE_MIGRATIONS, SQLITE_VERSION } from "../db/sqliteMigrations.js";

/** A migration name, safe to sit inside a single-quoted SQL string. */
const sqlName = (name) => name.replace(/'/g, "''");

/**
 * The settings a brand-new site starts with.
 *
 * Node's installer writes these through the repository; PHP has no repository,
 * so it writes the same two rows here. `theme` is the JSON-encoded default the
 * front end reads, and `schema_version` is what databases from before the
 * ledger used — `currentVersion()` falls back to it.
 */
function defaultSettings(version, dialect = "mysql") {
  // SQLite spells it `INSERT OR IGNORE`. Node's own sqlite migrations carry the
  // row inline; MySQL's do not, so it is added here for both.
  const insert = dialect === "sqlite" ? "INSERT OR IGNORE" : "INSERT IGNORE";
  return [
    `${insert} INTO settings (setting_key, value) VALUES ('theme', '"dark"')`,
    `${insert} INTO settings (setting_key, value) VALUES ('schema_version', '${version}')`,
  ];
}

/** Every statement, in order, for a MariaDB/MySQL database. */
export function mysqlSchemaStatements() {
  const statements = [...BASE_STATEMENTS];
  for (const migration of MIGRATIONS) {
    for (const statement of migration.up.statements ?? []) statements.push(statement);
    statements.push(
      `INSERT IGNORE INTO schema_migrations (version, name) VALUES (${migration.version}, '${sqlName(migration.name)}')`,
    );
  }
  statements.push(...defaultSettings(LATEST_VERSION));
  return statements;
}

/** Every statement, in order, for a SQLite database. */
export function sqliteSchemaStatements() {
  // Node's sqlite migrator creates its ledger itself, before running anything
  // (MySQL's is one of the BASE_STATEMENTS). PHP has to do the same, or the
  // first ledger row has no table to go into.
  const statements = [
    "CREATE TABLE IF NOT EXISTS pb_schema_migrations (version INTEGER PRIMARY KEY, name TEXT NOT NULL)",
  ];
  for (const migration of SQLITE_MIGRATIONS) {
    for (const statement of migration.statements) statements.push(statement);
    statements.push(
      `INSERT OR IGNORE INTO pb_schema_migrations (version, name) VALUES (${migration.version}, '${sqlName(migration.name)}')`,
    );
  }
  statements.push(...defaultSettings(SQLITE_VERSION, "sqlite"));
  return statements;
}

/** Both lists, plus the versions they leave the database at. */
export function phpSchema() {
  return {
    mysql: { version: LATEST_VERSION, statements: mysqlSchemaStatements() },
    sqlite: { version: SQLITE_VERSION, statements: sqliteSchemaStatements() },
  };
}

/** A PHP array literal for one list, wrapped so it stays readable in api.php. */
export function phpArrayLiteral(statements, indent = "    ") {
  const lines = statements.map(
    (statement) =>
      `${indent}  ${phpString(statement.trim().replace(/;?\s*$/, ""))},`,
  );
  return `[\n${lines.join("\n")}\n${indent}]`;
}

/**
 * A PHP single-quoted string. PHP's single quotes only escape `\` and `'`, so
 * nothing else has to be touched — no `$`, no `{}` interception, which matters
 * because these statements contain both.
 */
export function phpString(value) {
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

/** The whole block the export injects into api.php, markers included. */
export function phpSchemaBlock() {
  const schema = phpSchema();
  return [
    "/* PB-SCHEMA:START — generated by `npm run export:static -- --php`.",
    " * Do not edit: it is server/db/schema.js, migrations.js and sqliteMigrations.js",
    " * as SQL. Edit those and export again. */",
    "$SCHEMA = [",
    `  'mysql' => ${phpArrayLiteral(schema.mysql.statements, "  ")},`,
    `  'sqlite' => ${phpArrayLiteral(schema.sqlite.statements, "  ")},`,
    `  'mysqlVersion' => ${schema.mysql.version},`,
    `  'sqliteVersion' => ${schema.sqlite.version},`,
    "];",
    "/* PB-SCHEMA:END */",
  ].join("\n");
}
